"""Seed gazetteer for Urdu NER (BIO tags PER / LOC / ORG / MISC).

Entries are written as they appear in BBC Urdu (multi-word entries are
separated by spaces) and are matched against the *whitespace words* of the
original sentence (see a1_bridge), longest match first.

Required coverage: >= 50 Pakistani persons, >= 50 locations, >= 30 organisations.
"""
from __future__ import annotations


def _lines(s: str) -> list[str]:
    return [ln.strip() for ln in s.strip().splitlines() if ln.strip()]


