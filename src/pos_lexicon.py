def verb_forms(lemma: str) -> list[str]:
    """Regular inflection of an infinitive: root + {نا نے نی تا تے تی تیں ...}."""
    if not lemma.endswith("نا") or len(lemma) < 3:
        return [lemma]
    r = lemma[:-2]
    forms = [r, r + "نا", r + "نے", r + "نی", r + "تا", r + "تے", r + "تی", r + "تیں",
             r + "کر"]
    if r[-1] in "او":                       # vowel-final root (بتا، سو)
        forms += [r + "یا", r + "ئی", r + "ئے", r + "ئیں", r + "ؤ", r + "ؤں", r + "یے"]
    else:                                     # consonant-final root (کہ، دیکھ)
        forms += [r + "ا", r + "ی", r + "ے", r + "یں", r + "و", r + "وں", r + "یے"]
    return forms


